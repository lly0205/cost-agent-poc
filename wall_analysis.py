segs = []
for item in raw:
    sid, x1, y1, x2, y2 = item
    dx = abs(x2 - x1)
    dy = abs(y2 - y1)
    length = math.sqrt(dx*dx + dy*dy)
    if dy < 1:
        kind = 'H'
        coord = y1
    elif dx < 1:
        kind = 'V'
        coord = x1
    else:
        kind = 'D'
        coord = None
    segs.append({'id': sid, 'x1': x1, 'y1': y1, 'x2': x2, 'y2': y2,
                 'dx': dx, 'dy': dy, 'length': length, 'kind': kind, 'coord': coord})

